#!/usr/bin/env python3
"""Generates src/panel/agent-icon-data.ts from Orca's own agent icons.

Also generates src/panel/lucide-data.ts: the Lucide shapes the panel draws, from the lucide-react
version Orca pins (its pnpm-lock.yaml), fetched with `npm pack`.

Reads an Orca checkout (ORCA_SRC, default ~/Space/Development/_external/orca):
- SVG glyphs: JSX of the icon components, turned into plain SVG strings;
- PNG favicons: the files Orca bundles for its other agents, as data URIs.
Run after updating the checkout. Do not edit the generated file by hand.
"""
import base64
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from xml.dom import minidom

ORCA = Path(os.environ.get("ORCA_SRC", Path.home() / "Space/Development/_external/orca"))
RENDERER = ORCA / "src/renderer/src/components"
GLYPHS = RENDERER / "agent/icons/agent-icon-glyphs.tsx"
PROVIDERS = RENDERER / "status-bar/accounts/provider-icons.tsx"
FAVICONS = RENDERER / "agent/icons/agent-favicon-assets.ts"
PNG_DIR = ORCA / "src/shared/agent-icons"
OUT = Path(__file__).parent / "src/panel/agent-icon-data.ts"
LUCIDE_OUT = Path(__file__).parent / "src/panel/lucide-data.ts"
FONT_OUT = Path(__file__).parent / "src/panel/font-data.ts"
REPO_ICON_LIST = RENDERER / "repo/repo-icon.tsx"

# Lucide components the panel's own chrome draws (see PANEL_ICONS in src/panel/icons.ts).
PANEL_LUCIDE = [
    "ChevronRight", "Folder", "FolderOpen", "Book", "GitBranch", "Terminal", "ExternalLink", "ListFilter",
    "ChevronsDownUp", "ChevronsUpDown", "Ellipsis", "ArrowLeft", "Check", "MessageSquare",
    "Search", "SquareTerminal", "CornerDownLeft", "X",
]

# agent id -> (source file, component function). Ids Orca maps to the same component share one glyph.
SVG_SOURCES = {
    "claude": (PROVIDERS, "ClaudeIcon"),
    "claude-agent-teams": (PROVIDERS, "ClaudeIcon"),
    "codex": (PROVIDERS, "OpenAIIcon"),
    "droid": (PROVIDERS, "DroidIcon"),
    "pi": (GLYPHS, "PiIcon"),
    "omp": (GLYPHS, "OmpIcon"),
    "aider": (GLYPHS, "AiderIcon"),
    "kilo": (GLYPHS, "KiloIcon"),
    "copilot": (GLYPHS, "CopilotIcon"),
    "opencode": (GLYPHS, "OpenCodeIcon"),
    "opencode2": (GLYPHS, "OpenCodeIcon"),
}

ATTRS = {
    "fillRule": "fill-rule", "clipRule": "clip-rule", "fillOpacity": "fill-opacity",
    "stopColor": "stop-color", "textAnchor": "text-anchor",
}


def component_svg(source: str, name: str) -> str:
    start = source.index(f"export function {name}")
    block = source[start:]
    svg_start = block.index("<svg")
    svg_end = block.index("</svg>") + len("</svg>")
    return block[svg_start:svg_end]


def to_svg(jsx: str) -> str:
    text = jsx
    text = re.sub(r"\s(?:className|style)=\{\{[^}]*\}\}", "", text)
    text = re.sub(r"\s(?:className|style)=\{[^}]*\}", "", text)
    text = re.sub(r"\s(?:height|width)=\{size\}", "", text)
    text = text.replace("{`url(#${gradientId})`}", '"url(#omp-gradient)"').replace("{gradientId}", '"omp-gradient"')
    text = re.sub(r"\saria-hidden(?=[\s>/])", ' aria-hidden="true"', text)
    for jsx_name, svg_name in ATTRS.items():
        text = text.replace(f" {jsx_name}=", f" {svg_name}=")
    # Sizes come from CSS: drop width/height on the root only.
    root_end = text.index(">")
    root = re.sub(r"\s(?:width|height)=\"[^\"]*\"", "", text[:root_end])
    text = root + text[root_end:]
    text = re.sub(r"\s+", " ", text).replace("> <", "><")
    minidom.parseString(text)  # fails loudly on anything that is not well-formed XML
    if "{" in text or "$" in text:
        sys.exit(f"JSX left in SVG: {text[:200]}")
    return text


def png_icons() -> dict[str, str]:
    source = FAVICONS.read_text()
    files = dict(re.findall(r"import (\w+) from '[^']*/agent-icons/([\w-]+)\.png\?url'", source))
    mapping = re.findall(r"^\s*'?([\w-]+)'?: (\w+),?$", source, re.M)
    icons = {}
    for agent, var in mapping:
        if var in files:
            data = (PNG_DIR / f"{files[var]}.png").read_bytes()
            icons[agent] = "data:image/png;base64," + base64.b64encode(data).decode()
    return icons


def main() -> None:
    svgs = {}
    for agent, (path, name) in SVG_SOURCES.items():
        svgs[agent] = to_svg(component_svg(path.read_text(), name))
    pngs = png_icons()
    lines = [
        "// Generated by build.py from Orca's agent icons. Do not edit.",
        "",
        "/** Inline SVG glyphs, as Orca draws them (some use currentColor). */",
        "export const AGENT_SVGS: Record<string, string> = {",
    ]
    lines += [f"  {agent!r}: {svg!r}," for agent, svg in sorted(svgs.items())]
    lines += ["}", "", "/** Bundled PNG favicons as data URIs. */", "export const AGENT_PNGS: Record<string, string> = {"]
    lines += [f"  {agent!r}: {uri!r}," for agent, uri in sorted(pngs.items())]
    lines += ["}", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.name}: {len(svgs)} svg, {len(pngs)} png, {OUT.stat().st_size} bytes")


NODE_DUMP = """
const fs = require('fs'); const [dir, ...files] = process.argv.slice(1);
const out = {};
for (const f of files) {
  const src = fs.readFileSync(`${dir}/icons/${f}.js`, 'utf8');
  const nodes = eval(src.slice(src.indexOf('const __iconNode = ') + 19, src.indexOf('];\\nconst') + 1));
  out[f] = nodes.map(([tag, { key, ...attrs }]) => [tag, attrs]);
}
console.log(JSON.stringify(out));
"""


def lucide_version() -> str:
    lock = (ORCA / "pnpm-lock.yaml").read_text()
    return re.search(r"^  lucide-react@([\d.]+):", lock, re.M).group(1)


def lucide_shapes() -> tuple[str, dict[str, list]]:
    """Shapes of every icon the panel draws, keyed by the component name Orca imports."""
    repo_names = re.findall(r"name: '(\w+)'", REPO_ICON_LIST.read_text())
    wanted = list(dict.fromkeys(["Folder", *repo_names, *PANEL_LUCIDE]))
    version = lucide_version()
    with tempfile.TemporaryDirectory() as tmp:
        tarball = subprocess.run(["npm", "pack", f"lucide-react@{version}", "--silent"], cwd=tmp, check=True, capture_output=True, text=True).stdout.strip().splitlines()[-1]
        subprocess.run(["tar", "xzf", tarball], cwd=tmp, check=True)
        dist = Path(tmp) / "package/dist/esm"
        exports = (dist / "lucide-react.js").read_text() + (dist / "icons/index.js").read_text()
        files = {}
        for name in wanted:
            # Aliases (Code2 is CodeXml) sit in one export line; the file is the line's last path.
            match = re.search(rf"default as {name}[ ,][^;]*?from './(?:icons/)?([\w-]+)\.js'", exports)
            if not match:
                sys.exit(f"lucide-react {version} has no {name}")
            files[name] = match.group(1)
        dump = subprocess.run(["node", "-e", NODE_DUMP, str(dist), *set(files.values())], check=True, capture_output=True, text=True).stdout
    by_file = json.loads(dump)
    return version, {name: by_file[file] for name, file in files.items()}


def write_lucide() -> None:
    version, shapes = lucide_shapes()
    lines = [
        f"// Generated by build.py from lucide-react {version}, the version Orca pins. Do not edit.",
        "",
        "export type Shape = readonly [string, Record<string, string>]",
        "",
        "/** Lucide shapes by component name; the project icons are Orca's own list (`repo-icon.tsx`). */",
        "export const LUCIDE: Record<string, readonly Shape[]> = {",
    ]
    for name, nodes in shapes.items():
        items = ", ".join(f"[{tag!r}, {json.dumps(attrs)}]" for tag, attrs in nodes)
        lines.append(f"  {name}: [{items}],")
    lines += ["}", ""]
    LUCIDE_OUT.write_text("\n".join(lines))
    print(f"{LUCIDE_OUT.name}: lucide-react {version}, {len(shapes)} icons")


def write_font() -> None:
    # The panel's CSP allows `font-src data:` only, and Orca's `--font-sans` is not among the tokens plugins get.
    data = base64.b64encode((ORCA / "src/renderer/src/assets/fonts/Geist-Variable.woff2").read_bytes()).decode()
    FONT_OUT.write_text(
        "// Generated by build.py from Orca's Geist-Variable.woff2. Do not edit.\n\n"
        f"export const GEIST_URL = 'data:font/woff2;base64,{data}'\n"
    )
    print(f"{FONT_OUT.name}: {len(data)} bytes")


write_lucide()
write_font()
main()
